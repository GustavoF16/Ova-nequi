create table if not exists public.surveys (
  id bigint generated by default as identity primary key,
  user_email text not null,
  respuesta1 text not null,
  respuesta2 text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.simulations (
  id bigint generated by default as identity primary key,
  user_email text not null,
  numero text not null,
  monto numeric not null check (monto > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  user_email text not null,
  nombre text not null,
  fecha text not null,
  created_at timestamptz not null default now()
);

create index if not exists surveys_user_email_idx on public.surveys (user_email);
create index if not exists simulations_user_email_idx on public.simulations (user_email);
create index if not exists certificates_user_email_idx on public.certificates (user_email);

alter table public.surveys enable row level security;
alter table public.simulations enable row level security;
alter table public.certificates enable row level security;

grant insert on table public.surveys to anon, authenticated;
grant insert on table public.simulations to anon, authenticated;
grant insert on table public.certificates to anon, authenticated;

create policy "Allow anonymous survey submissions"
  on public.surveys for insert to anon, authenticated
  with check (true);

create policy "Allow anonymous simulation submissions"
  on public.simulations for insert to anon, authenticated
  with check (true);

create policy "Allow anonymous certificate submissions"
  on public.certificates for insert to anon, authenticated
  with check (true);
